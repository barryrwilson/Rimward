/**
 * Issue #270 live check — real game boot in disposable Chromium.
 *
 * Generates every system's record bank (authored and generated alike) inside the
 * running app's own module graph — the same ensureBank the game uses — and
 * asserts no fallback `<Role> <sysId>-<n>` label reaches names, Q-ship covers,
 * or the scanner DOM.
 *
 * Run: npm run test:npc-names-live
 */
import assert from 'node:assert/strict';
import { resolve } from 'node:path';

// Keep the disposable profile outside Vite's watched root: Windows locks
// Chrome's Cookies file and Vite's watcher throws EBUSY on it.
process.env.ISSUE74_OUT = process.env.ISSUE270_OUT || resolve('../issue-270-live-out');
delete process.env.ISSUE74_RESUME_PROFILE;
delete process.env.ISSUE74_PORT;
const { runLive } = await import('./issue-74-live-harness.mjs');

const FALLBACK = /^(Reaver|Freighter|Patrol|Miner|Hauler) [a-z0-9_]+-\d+$/;

await runLive('npc-names', async ({ c, result, checkpoint }) => {
  result.fixture = false;
  result.method = 'Real boot in disposable Chromium; every system record bank generated by the app module graph. No record names or DOM text are overwritten.';
  result.systems = await c.eval(`(async () => {
    const { SYSTEMS } = await import('/src/game/state.js');
    const { ensureBank, minerCountForCast } = await import('/src/game/world.js');
    const out = {};
    for (const [sysId, def] of Object.entries(SYSTEMS)) {
      const cast = def.cast || {};
      const expected = (cast.traders | 0) + (cast.pirates | 0) + (cast.patrols | 0)
        + minerCountForCast(cast) + (cast.ace ? 1 : 0);
      const bank = ensureBank(window.__ctx, sysId);
      out[sysId] = { expected, records: bank.map((r) => ({ name: r.name, role: r.role, cover: r.coverName ?? null, qship: !!r.qship })) };
    }
    return out;
  })()`);

  const systems = Object.keys(result.systems);
  assert.ok(systems.length >= 100, `all ${systems.length} systems generated in the browser`);

  let checked = 0;
  let covers = 0;
  for (const [sysId, entry] of Object.entries(result.systems)) {
    assert.equal(entry.records.length, entry.expected, `${sysId}: bank covers every cast slot`);
    const seen = new Set();
    for (const rec of entry.records) {
      assert.equal(typeof rec.name, 'string', `${sysId}: name string`);
      assert.ok(!FALLBACK.test(rec.name), `${sysId}: "${rec.name}" is not a fallback label`);
      assert.ok(!seen.has(rec.name), `${sysId}: "${rec.name}" unique`);
      seen.add(rec.name);
      checked++;
      if (rec.qship) {
        assert.equal(typeof rec.cover, 'string', `${sysId}: Q-ship cover present`);
        assert.ok(!FALLBACK.test(rec.cover), `${sysId}: cover "${rec.cover}" is readable`);
        assert.ok(!seen.has(rec.cover), `${sysId}: cover "${rec.cover}" unique`);
        seen.add(rec.cover);
        covers++;
      }
    }
  }
  assert.ok(checked >= 500, `generated ${checked} records`);
  assert.ok(covers >= 40, `generated ${covers} Q-ship covers`);

  result.checked = checked;
  result.covers = covers;
  result.scannerText = await c.eval('document.body.innerText');
  const fallbackRows = result.scannerText.split(/\r?\n/).filter((line) => FALLBACK.test(line.trim()));
  assert.deepEqual(fallbackRows, [], 'no fallback label appears anywhere in the HUD/panel DOM');
  assert.deepEqual(result.consoleErrors, [], 'no console errors during boot');
  assert.deepEqual(result.exceptions, [], 'no uncaught exceptions during boot');

  await checkpoint('all-system-banks');
});
